#!/usr/bin/env python3
"""生成原创合成练习；只给客户材料，不生成四格、规则、手册或答案。"""
import argparse
import csv
from pathlib import Path
from etl_project import init_project


def build_practice(output):
    root = Path(output).resolve()
    root.mkdir(parents=True, exist_ok=False)
    materials = root / "materials"
    exports = materials / "exports"
    exports.mkdir(parents=True)

    def text(name, body):
        (root / name).write_text(body.strip() + "\n", encoding="utf-8")

    def table(name, fields, rows):
        with (exports / name).open("w", encoding="utf-8", newline="") as handle:
            writer = csv.writer(handle)
            writer.writerow(fields)
            writer.writerows(rows)

    customers = [
        ["C001", "客户甲", "企业/维修|仅周末联系", ""],
        ["C002", "客户乙", "个人|勿发短信", ""],
        ["C003", "客户丙", "企业/维修", ""],
        ["C004", "客户丁", "个人|先邮件确认", ""],
        ["C005", "客户戊", "个人", ""],
        ["C006", "客户己", "企业/维修|勿打电话", ""],
        ["C007", "客户庚", "个人", ""],
        ["C008", "客户辛", "个人", ""],
    ]
    table("客户导出.csv", ["client_ref", "display_name", "labels", "alternate_contact"], customers)
    table("网点导出.csv", ["site_ref", "site_name"], [["S01", "南站服务点"], ["S02", "北站服务点"]])
    amounts = [("1000.00", "0.00"), ("200.00", "0.00"), ("350.50", "20.00"),
               ("80.00", "0.00"), ("0.00", "0.00"), ("0.00", "10.00"),
               ("100.00", "0.00"), ("500.00", "0.00"), ("99.90", "0.00"),
               ("0.00", "0.00"), ("600.00", "0.00"), ("0.00", "0.00"),
               ("120.00", "120.00"), ("300.00", "0.00"), ("0.00", "0.00"),
               ("800.10", "0.00"), ("60.00", "0.00"), ("100.00", "0.00")]
    states = ["已完工", "已完工", "已完工", "处理中", "已取消", "已完工", "待验收", "已完工",
              "已完工", "处理中", "已完工", "已取消", "已完工", "已完工", "处理中", "已完工", "已完工", "已完工"]
    rows = []
    for i, ((received, returned), state) in enumerate(zip(amounts, states), 1):
        date = f"2026-10-{i:02}"
        if i == 3:
            date = "2026/10/03"
        elif i == 8:
            date = "20261008"
        elif i == 18:
            date = "2026-11-01"
        rows.append([f"J{i:03}", f"C{(i-1) % 8+1:03}", "S01" if i % 2 else "S02",
                     date, state, received, returned, "补退上期款" if i == 6 else ""])
    rows += [["J019", "C099", "S01", "2026-10-19", "已完工", "160.00", "0.00", "历史账户"],
             ["J020", "C003", "S01", "2026-10-20", "已完工", "210.00", "0.00", ""],
             ["J020", "C003", "S01", "2026-10-20", "已完工", "220.00", "0.00", ""],
             list(rows[1]), list(rows[15])]
    table("工单导出.csv", ["job_ref", "client_ref", "site_ref", "opened_at", "state", "received", "returned", "note"], rows)
    table("现场补登簿.csv", ["job_ref", "description"], [["J019", "旧客户资料未随导出提供"], ["P001", "合作维修商现场受理"]])
    text("00-开始练习.md", """
# 澄川设备维修：一次数据交付练习

本案例所有客户、角色、邮件和数据均为原创虚构。它不属于课程作业，不对应真实客户。
当前状态：**尚未开始**。工具包位置已登记，未生成四格、定制手册、清洗规则或答案。

你扮演 FDE，AI 帮你查看数据和执行；你负责确认背景、判断规则、验收证据。

先读 `materials/01-客户任务.md` 与 `02-导出说明与旧字典.md`。
其余核实记录和 CSV 也是可用客户材料，遇到疑点时可以查阅，不能把它们登记成本人做过的访谈。

你要交：数据台账和带证据的剖析、规则及依据、处理结果与逐条去向、两段对账、限定范围的网点统计和一段客户可读结论。
工具包不会自动完成全部验收；未覆盖的检查需 AI 编写项目检查，你亲自抽查。

第一步只做：请 AI 阅读客户材料，起草四格背景，你核对后再决定是否生成定制手册。
不要先要求 AI 一口气把整单做完，也不要先读取工具包的 practice.py 来猜设计者的意图。

可以直接对 AI 说：
“开始澄川这个客户。先按工具包读取 materials/，只起草四格背景，每条有出处，等我确认。”

做完四格后停下来。你可以在当前导师会话中提交作答、提疑问或请求反馈。
这是工具试用练习，不登记为已经掌握，也不登记为正式作业提交。
""")
    text("materials/01-客户任务.md", """
# 客户任务（案例设计者编写的虚构邮件）

发件人：澄川业务负责人 方经理；日期：2026-11-04。

我们有南站、北站两个直营网点，另外也交给合作维修商处理部分工单。
想先核对：2026 年 10 月新建的工单中，截至本次导出状态已完工的有多少单、净收款多少，两个直营网点分别是多少。
后续用这个结果检查直营网点台账，决定能否安排同事试用问数。不是按它评价维修工绩效。

这次先做文件演示，不连接真实系统，不联系客户，不发消息。
希望能解释每一条输入去了哪里、金额为什么这样算、哪些部分尚未拿到。
不要把演示的已覆盖数据写成全公司的全部维修业务。

可用材料：系统管理员的导出说明、旧字典、既有核实记录和原始 CSV。
原始材料不得覆盖，任何推断单列；统计口径要能追到材料中的明确依据。
""")
    text("materials/02-导出说明与旧字典.md", """
# 导出说明与旧字典

系统管理员 顾工，2026-11-03 09:00 导出。

工单按创建日期提取：2026-10-01（含）至 2026-11-02（不含），状态是导出时的快照。
本次仅提供两个直营网点在新工单系统内的记录；合作维修商系统的工单未提供，未提供部分规模未知。
日期按本地自然日理解，没有精确时间，也没有工单状态历史。
导出过程分两次拼接，没有逐条更新时间。

文件用途：客户、网点、工单导出用于拟议导入；现场补登簿是人工核对材料，不导入业务表。
客户资料仅提供当前可导出的账户，历史账户资料可能不在其中。

旧字段字典（2024-06 版，未承诺已同步当前系统）：

| 文件／字段 | 旧说明 |
| --- | --- |
| 客户 client_ref | 文本客户号 |
| labels | 单个分类，只含个人、企业 |
| alternate_contact | 可空备用联系方式 |
| 网点 site_ref | 文本网点号 |
| 工单 job_ref | 工单号，应唯一 |
| client_ref、site_ref | 对应客户和网点 |
| opened_at | 完工日期，统一 YYYY-MM-DD |
| state | 已完工、处理中、已取消 |
| received、returned | 收款和退款，整数分 |
| note | 可空备注 |

字典存在更新滞后的可能，冲突时先对数据剖析，并查核实记录，不直接按旧字典转换。
""")
    text("materials/03-既有核实记录.md", """
# 既有核实记录

以下为案例设计者编写的虚构邮件往来，不是练习者已经进行的访谈。
可以作为本案例证据引用；提问之外的新事实不得自行编造。

## IT-01 顾工，2026-11-04

`opened_at` 记录工单创建日，旧字典把它写成完工日期是错的。
当前导出不含 completed_at，不能据此计算“10 月实际完工的全部工单”。三种日期写法均为年、月、日。
`received`、`returned` 本批都是元，最多两位小数；旧字典的整数分说明未更新。
`待验收` 是后来新增的状态，还不算已完工。

J019 是历史已注销账户对应的真实工单；本次未取得 C099 的客户档案。
两条 J020 缺少可判定先后的更新时间，不能按金额大小或文件先后擅自选一条。

## BIZ-01 方经理，2026-11-04

本轮统计按“10 月新建，导出时已完工”的工单集合，不当作“10 月完工流量”或“10 月底状态”。
已完工工单净收款＝收到金额减累计已退金额；全额退款仍保留已完工工单身份，净额为零。
处理中、待验收、已取消均不计入这个已完工统计集合，原始记录仍保留。
J006 的退款大于收款暂时没有单据可解释；本轮不改值、不删除，保留异常标记并在结论旁说明。
这只是收款台账口径，不认定为财务收入。

完全相同的重复输入保留一条，其余记去重；同号内容不同且无法选定权威版本时，本轮整组暂隔离。
目标模型的关联约束不满足时可暂隔离，保留原文和原因；隔离不能写成工单本身无效。
未来拿到补充材料再复核，不因为这次未取得就说记录或文件不存在。

## OPS-01 服务主管，2026-11-04

合法分类是“个人”和“企业/维修”，斜杠是分类名称的一部分。labels 用竖线分隔分类与手记。
“勿发短信”“勿打电话”“仅周末联系”都应作为联系限制保留；“先邮件确认”是服务手记，不能直接升级成禁止一切联系。
备用联系方式为空是合法情况，不补造号码。各段都须保留来源和完整原文。
""")
    text("materials/04-目标数据约定.md", """
# 本轮目标数据约定（虚构项目的已给定接口条件）

金额存为整数分，日期存为 YYYY-MM-DD，标识均为文本。
正常业务表：客户 client_id（唯一）；网点 site_id（唯一）；工单 job_id（唯一）、client_id、site_id、created_on、status、received_cents、returned_cents、note。
工单 client_id、site_id 必须可关联已导入客户与网点。不是让你编造缺失档案。
状态映射：已完工→completed；处理中→in_progress；待验收→awaiting_acceptance；已取消→cancelled。
分类、手记和联系限制可另存关联表，保留原始字段和每段的来源；关联后不得放大工单计数。

每条原始记录（文件名＋不含表头的 CSV 记录序号，从 1 起）只能归入接受、隔离、去重之一。
隔离记录至少带 source_file、source_row、reason_code、raw_record。正常接受集合还要与落库数据核对身份和关键字段。
输出的文件名、表结构扩展和技术实现由你与 AI 选择，写清约定即可；可使用 SQLite 或自己熟悉的本地数据库。
报告必须区分：数据发现、既有核实记录、自己的推断、尚待核实；补登簿只做对照。
任何未覆盖来源不当零、不估算，不把一个状态快照当历史状态变迁。
""")
    init_project(root, "澄川-ETL工作手册.md", "artifacts/b01", "check_config.json", "learning")
    text("AGENTS.md", (root / "AGENTS.md").read_text() + """

## 本练习的额外约定

- 材料在 materials/；先读 00-开始练习.md，仅起草四格背景并等待本人确认。
- 不读取工具包 practice.py、演示答案或练习目录外的导师参考答案来替代分析。
- 现有核实记录是设计者提供的情境材料，不能登记成本人已经访谈、已确认、已执行的成果。
- 不得提前生成定制手册或清洗全部数据；未取得证据就写待核，不扮演客户编造答复。
""")
    print(f"练习已准备：{root / '00-开始练习.md'}；尚未开始作答。")
    return root


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, help="全新的练习目录")
    args = parser.parse_args()
    try:
        build_practice(args.output)
    except (OSError, ValueError) as exc:
        print(f"练习未生成：{exc}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
